def save_backup(
    score_configs: list[dict],
    prompts: list[dict],
    evaluator_docs: dict,
    output_path: Path,
) -> None:
    """Save evaluator and prompt configurations to JSON backup file.

    Args:
        score_configs: List of score configurations
        prompts: List of prompt configurations
        evaluator_docs: Documentation of evaluator functions
        output_path: Path to save backup file

    """
    backup_data = {
        "metadata": {
            "backup_timestamp": datetime.now(timezone.utc).isoformat(),
            "score_config_count": len(score_configs),
            "prompt_count": len(prompts),
            "langfuse_host": os.getenv("LANGFUSE_HOST", "http://localhost:3000"),
            "description": (
                "Backup of Langfuse configurations for LLM-as-a-Judge evaluation. "
                "Score configs define score types/ranges. Prompts define evaluation prompts. "
                "Evaluator functions are Python code in app/shared/services/g_eval/."
            ),
        },
        "score_configs": score_configs,
        "prompts": prompts,
        "evaluator_functions": evaluator_docs,
    }

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Save to JSON file
    with output_path.open("w") as f:
        json.dump(backup_data, f, indent=2, default=str)

    print(f"\nBackup saved to {output_path}")
    print(f"  - {len(score_configs)} score configurations")
    print(f"  - {len(prompts)} prompt configurations")
    print(f"  - Evaluator function documentation")

    # Show summary of G-Eval configs
    g_eval_configs = [c for c in score_configs if c["name"].startswith("g_eval_")]
    if g_eval_configs:
        print(f"\nG-Eval Score Configs ({len(g_eval_configs)}):")
        for config in g_eval_configs:
            print(f"  - {config['name']}: {config['dataType']}")
            if "minValue" in config and "maxValue" in config:
                print(f"    Range: {config['minValue']} - {config['maxValue']}")


async def main() -> None:
    """Main backup execution function."""
    # Get credentials
    public_key, secret_key, host = get_langfuse_credentials()

    print("=" * 70)
    print("Langfuse LLM-as-a-Judge Evaluator Backup")
    print("=" * 70)
    print()

    # Create HTTP client with authentication
    async with httpx.AsyncClient(
        auth=(public_key, secret_key),
        timeout=30.0,
    ) as client:
        # Fetch score configs and prompts
        score_configs = await fetch_score_configs(client, host)
        prompts = await fetch_prompts(client, host)

        # Document evaluator functions
        print("\nDocumenting evaluator functions...")
        evaluator_docs = document_evaluator_functions()
        print(f"Documented {len(evaluator_docs['agent_types'])} agent types")

        # Save backup
        output_path = Path(__file__).parent.parent / "data" / "langfuse_evaluators_backup.json"
        save_backup(score_configs, prompts, evaluator_docs, output_path)

        print("\n" + "=" * 70)
        print("Backup complete!")
        print("=" * 70)
        print()
        print("To restore:")
        print("  1. Score configs: poetry run python scripts/setup_langfuse_score_configs.py")
        print("  2. Prompts: Use Langfuse UI or API to restore prompts")
        print("  3. Evaluators: Already in source code (app/shared/services/g_eval/)")


if __name__ == "__main__":
    import asyncio

    asyncio.run(main())
