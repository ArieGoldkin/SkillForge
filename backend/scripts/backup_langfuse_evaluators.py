#!/usr/bin/env python3
"""Backup Langfuse LLM-as-a-Judge evaluator configurations.

This script backs up all Langfuse configurations used for LLM-as-a-Judge evaluation:
1. Score Configs - Define score types, ranges, and metadata
2. Prompts - Langfuse prompts that may be used by evaluators
3. Evaluator Documentation - Documents which Python evaluators are used and their parameters

Note: The actual evaluator functions are Python code (in app/shared/services/g_eval/),
      not stored in Langfuse. This backup captures the Langfuse-side configuration.

Usage:
    poetry run python scripts/backup_langfuse_evaluators.py

Environment Variables:
    LANGFUSE_PUBLIC_KEY: Langfuse public API key
    LANGFUSE_SECRET_KEY: Langfuse secret API key
    LANGFUSE_HOST: Langfuse server URL (default: http://localhost:3000)

Output:
    backend/data/langfuse_evaluators_backup.json
"""

import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import httpx
from dotenv import load_dotenv

# Load environment variables from .env file
load_dotenv()


def get_langfuse_credentials() -> tuple[str, str, str]:
    """Get Langfuse credentials from environment variables.

    Returns:
        Tuple of (public_key, secret_key, host)

    Raises:
        SystemExit: If credentials are not configured

    """
    public_key = os.getenv("LANGFUSE_PUBLIC_KEY")
    secret_key = os.getenv("LANGFUSE_SECRET_KEY")
    host = os.getenv("LANGFUSE_HOST", "http://localhost:3000")

    if not public_key or not secret_key:
        print("Error: Langfuse credentials not configured")
        print("Required environment variables:")
        print("  - LANGFUSE_PUBLIC_KEY")
        print("  - LANGFUSE_SECRET_KEY")
        print("  - LANGFUSE_HOST (optional, default: http://localhost:3000)")
        sys.exit(1)

    return public_key, secret_key, host


async def fetch_score_configs(client: httpx.AsyncClient, host: str) -> list[dict]:
    """Fetch all score configurations from Langfuse.

    Score configs define the types and ranges of scores used by evaluators.

    Args:
        client: Configured HTTP client with auth
        host: Langfuse server URL

    Returns:
        List of score configurations

    """
    url = f"{host}/api/public/score-configs"

    print(f"Fetching score configurations from {url}...")

    response = await client.get(url)
    response.raise_for_status()

    data = response.json()

    # The response should contain a list of score configs
    # Structure: {"data": [...], "meta": {...}}
    score_configs = data.get("data", [])

    print(f"Found {len(score_configs)} score configurations")

    # Filter for G-Eval related configs
    g_eval_configs = [c for c in score_configs if c["name"].startswith("g_eval_")]
    print(f"  - {len(g_eval_configs)} G-Eval score configs")

    return score_configs


async def fetch_prompts(client: httpx.AsyncClient, host: str) -> list[dict]:
    """Fetch all prompts from Langfuse.

    Many evaluators reference prompts, so we backup those too.

    Args:
        client: Configured HTTP client with auth
        host: Langfuse server URL

    Returns:
        List of prompt configurations

    """
    url = f"{host}/api/public/v2/prompts"

    print(f"\nFetching prompt configurations from {url}...")

    response = await client.get(url, params={"limit": 100})
    response.raise_for_status()

    data = response.json()
    prompts = data.get("data", [])

    print(f"Found {len(prompts)} prompt configurations")

    return prompts


